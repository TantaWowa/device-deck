import { renderCask } from "./cask-template";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import { verifyManifest } from "../../packages/installer/src/index";
import config from "../../config/releases/keygen.json";
import distribution from "../../config/releases/distribution.json";
const {values}=parseArgs({options:{manifest:{type:"string",multiple:true},output:{type:"string",default:"work/distribution/homebrew/Casks/device-deck.rb"}}});
if(!values.manifest?.length)throw new Error("Supply --manifest FILE for each signed public architecture. This generates a cask; it does not publish a tap.");
const trust={accountId:config.live.accountId,productId:config.live.productId,metadataPublicKey:distribution.publicKey};
const manifests=await Promise.all(values.manifest.map(async file=>verifyManifest(JSON.parse(await readFile(file,"utf8")),trust)));
if(manifests.some(m=>m.format!=="pkg"||m.mode!=="live"||m.channel!=="stable"||m.signing!=="developer-id-notarized"||m.minimumOS!=="14.0"))throw new Error("Casks require signed/notarized live stable packages for the supported minimum macOS version.");
if(new Set(manifests.map(m=>m.version)).size!==1||new Set(manifests.map(m=>m.arch)).size!==manifests.length)throw new Error("Supply one consistent version and one manifest per architecture.");
const cask = renderCask(manifests, trust);
await mkdir(path.dirname(values.output),{recursive:true});
await writeFile(values.output,cask);
console.log(path.resolve(values.output));
