import assert from "node:assert/strict";
import { mkdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "vite";
import { chromium, expect } from "@playwright/test";
import { pairedDecks } from "../tests/decks";

const stage = path.resolve("work/deck-sharing-ui");
const output = path.resolve("outputs/deck-sharing");
await mkdir(output, { recursive: true });
await build({ root: path.resolve("apps/web"), logLevel: "warn", build: { outDir: stage, emptyOutDir: true, rollupOptions: { input: path.resolve("apps/web/local.html") } } });
await rename(path.join(stage, "local.html"), path.join(stage, "index.html"));
const f = await pairedDecks(stage);
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
const checks: string[] = [];
try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
  page.setDefaultTimeout(10000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const ticket = await (await f.local.request("/v1/browser-ticket", {})).json();
  await page.goto(`${f.local.address}/#ticket=${ticket.ticket}`);
  await expect(page.getByRole("combobox", { name: "Device host" })).toHaveValue("local");
  await expect(page.getByRole("row").filter({ hasText: "Local TV" })).toBeVisible();
  await page.getByRole("combobox", { name: "Device host" }).selectOption("ms");
  await expect(page.getByRole("heading", { name: "Capture Cards", exact: true })).toBeVisible();
  await expect(page.getByText("Host HDMI", { exact: true }).first()).toBeVisible();
  assert.equal(new URL(page.url()).searchParams.get("deck"), "ms");
  checks.push("local UI selects remote cards through the local daemon");
  await page.getByRole("navigation").getByRole("button", { name: /^Devices/ }).click();
  const row = page.getByRole("row").filter({ hasText: "Host TV" });
  await expect(row).toBeVisible();
  await row.getByRole("button", { name: "Reserve · Host TV", exact: true }).click();
  await page.getByLabel("Owner", { exact: true }).fill("Browser sharing proof");
  await page.getByLabel("Reason", { exact: true }).fill("Verify host-owned reservation");
  await page.getByRole("button", { name: "Reserve", exact: true }).click();
  await expect.poll(() => f.host.deck.store.sessions().filter((session) => session.state === "active").length).toBe(1);
  assert.equal(f.local.deck.store.sessions().length, 0);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("deck-remote-leases:ms") || "{}"));
  const acquired = Object.values(saved)[0] as { session: { id: string }; leaseToken: string };
  assert.ok(acquired.leaseToken);
  checks.push("browser reservation exists only in host SQLite and credentials are scoped to ms");
  await page.getByRole("combobox", { name: "Device host" }).selectOption("local");
  await expect(page.getByRole("combobox", { name: "Device host" })).toHaveValue("local");
  await page.getByRole("navigation").getByRole("button", { name: /^Devices/ }).click();
  await expect(page.getByRole("row").filter({ hasText: "Local TV" }).getByRole("button", { name: "Reserve · Local TV", exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Device host" }).selectOption("ms");
  await page.getByRole("navigation").getByRole("button", { name: /^Devices/ }).click();
  await row.getByRole("button", { name: "Reserved · Host TV", exact: true }).click();
  await page.getByRole("button", { name: "End session…", exact: true }).click();
  await page.getByRole("alertdialog", { name: "Confirm session change" }).getByRole("button", { name: "End session", exact: true }).click();
  await expect.poll(() => f.host.deck.store.session(acquired.session.id).state).toBe("closed");
  checks.push("switching Decks never reuses another host's lease; returning can release the original lease");
  await page.getByRole("navigation").getByRole("button", { name: "Capture Cards", exact: true }).click();
  await page.screenshot({ path: path.join(output, "remote-cards.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("combobox", { name: "Device host" })).toBeVisible();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(output, "remote-cards-mobile.png"), fullPage: true });
  checks.push("host selector stays accessible at phone width without horizontal overflow");
  await f.host.connections.revoke(f.grant.id);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Couldn't connect to Device Deck" })).toBeVisible();
  await page.getByRole("link", { name: "Return to this Mac" }).click();
  await expect(page.getByRole("combobox", { name: "Device host" })).toHaveValue("local");
  checks.push("revoked remote access shows a connection error and provides a local return route");
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, "report.json"), JSON.stringify({ fixture: true, checks }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} finally { await browser.close(); await f.close(); }
